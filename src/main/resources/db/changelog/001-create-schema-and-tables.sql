--changeset illya:001-create-schema
CREATE SCHEMA IF NOT EXISTS "ACC_APP_CHANGER";

--changeset illya:002-create-config-table
CREATE TABLE IF NOT EXISTS "ACC_APP_CHANGER"."APP_CHANGER_CONFIG"
(
    "ID"               BIGSERIAL PRIMARY KEY,
    "SYSTEMID"         VARCHAR(255),
    "EVENT_TYPE"       VARCHAR(255),
    "ENTITY_TYPE"      VARCHAR(255),
    "PROTOCOL_TYPE"    VARCHAR(255),
    "PROTOCOL_IN"      VARCHAR(255),
    "STATUS_IN"        SMALLINT,
    "PROTOCOL_OUT"     VARCHAR(255),
    "STATUS_OUT"       SMALLINT,
    "INS_TS"           TIMESTAMPTZ DEFAULT now(),
    "UPD_TS"           TIMESTAMPTZ DEFAULT now(),
    CONSTRAINT "UK_APP_CHANGER_CONFIG_SYSTEMID" UNIQUE ("SYSTEMID")
);

--changeset illya:003-create-trans-table
CREATE TABLE IF NOT EXISTS "ACC_APP_CHANGER"."APP_CHANGER_TRANS"
(
    "ID"               BIGSERIAL PRIMARY KEY,
    "PROTOCOL_TYPE"    VARCHAR(256),
    "SYSTEM_ID"        VARCHAR(256),
    "REQUEST_ID"       VARCHAR(256),
    "EVENT_TYPE"       VARCHAR(256),
    "RESP_DATA"        TEXT,
    "REQ_DATA"         TEXT,
    "STATUS"           VARCHAR(256),
    "RESP_CODE"        VARCHAR(16),
    "RESP_DESC"        VARCHAR(256),
    "INS_TS"           TIMESTAMPTZ DEFAULT now(),
    "UPD_TS"           TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "IDX_CHANGER_TRANS_STATUS" ON "ACC_APP_CHANGER"."APP_CHANGER_TRANS"("STATUS");
CREATE INDEX IF NOT EXISTS "IDX_CHANGER_TRANS_REQUEST_ID" ON "ACC_APP_CHANGER"."APP_CHANGER_TRANS"("REQUEST_ID");

--changeset illya:004-create-io-msgs-table
CREATE TABLE IF NOT EXISTS "ACC_APP_CHANGER"."APP_CHANGER_IO_MSGS"
(
    "ID"               BIGSERIAL PRIMARY KEY,
    "TRANS_ID"         BIGINT REFERENCES "ACC_APP_CHANGER"."APP_CHANGER_TRANS"("ID") ON DELETE CASCADE,
    "PROTOCOL_TYPE"    VARCHAR(64),
    "MSG_TYPE"         VARCHAR(64),
    "DIR"              VARCHAR(16),
    "MSG"              TEXT,
    "INS_TS"           TIMESTAMPTZ DEFAULT now(),
    "NODE_ID"          VARCHAR(8)
);

CREATE INDEX IF NOT EXISTS "IDX_CHANGER_IO_TRANS_ID" ON "ACC_APP_CHANGER"."APP_CHANGER_IO_MSGS"("TRANS_ID");